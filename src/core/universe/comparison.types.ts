/** Чем токен является. Разные архетипы зарабатывают по-разному и не сравниваются. */
export type AssetArchetype = 'protocol' | 'chain' | 'exchange' | 'infrastructure' | 'other';

/**
 * Состояние данных. Пробел не один: подтверждённый ноль, несклеенный протокол и
 * неприменимая бизнес-модель требуют разных действий, а общая корзина «нет данных»
 * делает очередь на ручной сбор ложной.
 */
export type DataState =
  | 'available'
  /** Ноль измерен и подтверждён источником: валидное значение, не пробел. */
  | 'known_zero'
  /** Монета не сопоставлена ни с одним протоколом: чинится склейкой. */
  | 'mapping_failed'
  /** Протокол найден, но выручки в сводках нет: чинится источником. */
  | 'source_missing'
  /** Адаптер сломан, числа устарели. */
  | 'source_stale'
  /** Сети платят валидаторам, а не держателям: нужны свои метрики, не эти. */
  | 'unsupported_business_model';

export interface ComparisonIdentity {
  /** Категория источника, как пришла. Живёт в поле sector кандидата. */
  rawSector: string | null;
  /** Все категории CoinGecko из карты, в которых состоит монета. */
  rawSectors: string[];
  /** Курируемая группа прямых конкурентов; ею группирует альфа. */
  comparisonGroup: string | null;
  assetArchetype: AssetArchetype;
}